// Textos de la interfaz del comensal en español, inglés, francés, portugués y alemán.
// El idioma se detecta solo desde la configuración del dispositivo (navigator.languages).
export type Idioma = 'es' | 'en' | 'fr' | 'pt' | 'de';
export const IDIOMAS: Idioma[] = ['es', 'en', 'fr', 'pt', 'de'];

/**
 * Resuelve el idioma del dispositivo: recorre las preferencias del navegador en orden
 * y toma la primera soportada. Si ninguna tiene traducción, inglés (idioma universal de respaldo).
 */
export function detectarIdioma(): Idioma {
  const prefs = typeof navigator !== 'undefined' ? (navigator.languages?.length ? navigator.languages : [navigator.language]) : [];
  for (const l of prefs) {
    const base = (l ?? '').toLowerCase().slice(0, 2) as Idioma;
    if (IDIOMAS.includes(base)) return base;
  }
  return 'en';
}

